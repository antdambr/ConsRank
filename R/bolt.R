# BOLT on the combined input matrix (internal)
# ══════════════════════════════════════════════════════════════════════════

boltcij <- function(cij, nj, full = FALSE, otp = TRUE, seeds = NULL, ps = FALSE) {

  N <- ncol(cij)
  S <- boltseeds(cij, seeds, full)
  tol <- 1e-10 * max(1, sum(abs(cij)))
  res <- bolt_run_impl(t(S), cij, full, otp, tol)
  top <- which(res$value >= max(res$value) - tol)
  cons <- unique(reordering(t(res$rankings[, top, drop = FALSE])))
  tau <- bolt_obj_impl(t(cons), cij) / (nj * N * (N - 1))
  if (ps) {
    message("BOLT: ", nrow(S), " starting solutions, ", nrow(cons),
            " solution(s) with Tau = ", round(max(tau), 5))
  }
  list(Consensus = cons, Tau = if (nrow(cons) == 1) tau else matrix(tau, ncol = 1))
}

# BOLT for the median constrained bucket order: exactly nb buckets (internal,
# used by mcbo)

boltcijbuckets <- function(cij, nb, nj, seeds = NULL, ps = FALSE) {

  N <- ncol(cij)
  S <- boltseeds(cij, seeds, full = FALSE)
  tol <- 1e-10 * max(1, sum(abs(cij)))
  res <- bolt_run_b_impl(t(S), cij, nb, tol)
  top <- which(res$value >= max(res$value) - tol)
  cons <- unique(reordering(t(res$rankings[, top, drop = FALSE])))
  tau <- bolt_obj_impl(t(cons), cij) / (nj * N * (N - 1))
  if (ps) {
    message("BOLT: ", nrow(S), " starting solutions, ", nrow(cons),
            " solution(s) with Tau = ", round(max(tau), 5))
  }
  list(Consensus = cons, Tau = if (nrow(cons) == 1) tau else matrix(tau, ncol = 1))
}


# Checks the pattern of bucket sizes and returns it in standard form: one
# element per bucket, a positive whole number where the size is prescribed and
# NA where it is free. A pattern whose given sizes do not use all the objects
# gets one free bucket at the end, so that c(1, 1, 1) with ten objects means
# three buckets of one object and a fourth one with the remaining seven

checkbucketsizes <- function(bucketsizes, N) {

  s <- bucketsizes
  if (is.logical(s) && all(is.na(s))) s <- as.numeric(s)   # rep(NA, b) is logical
  if (!is.numeric(s) || length(s) < 1) {
    stop("bucketsizes must be a numeric vector with one element per bucket")
  }
  given <- s[!is.na(s)]
  if (length(given) && (any(given != round(given)) || any(given < 1))) {
    stop("the sizes in bucketsizes must be whole numbers greater than zero, or NA for a free size")
  }
  s <- as.integer(round(s))
  if (sum(is.na(s)) == 0 && sum(s) < N) {
    s <- c(s, NA_integer_)                       # one free bucket takes the rest
  }
  nfree <- sum(is.na(s))                         # buckets whose size is free
  tot <- sum(s, na.rm = TRUE)                    # objects already assigned
  if (length(s) > N) {
    stop("bucketsizes cannot ask for more buckets than the number of objects (", N, ")")
  }
  if (tot + nfree > N) {
    stop("bucketsizes asks for more objects than there are (", N, ")")
  }
  if (nfree == 0 && tot != N) {
    stop("the sizes in bucketsizes must sum to the number of objects (", N, ")")
  }
  s
}

# BOLT for the median bucket order whose bucket sizes follow a pattern
# (internal, used by mcbo): same structure as boltcijbuckets, with the pattern
# in place of the number of buckets

boltcijpattern <- function(cij, sizes, nj, seeds = NULL, ps = FALSE) {

  N <- ncol(cij)
  S <- boltseeds(cij, seeds, full = FALSE)
  tol <- 1e-10 * max(1, sum(abs(cij)))
  res <- bolt_run_pat_impl(t(S), cij, as.integer(sizes), tol)
  if (all(!is.finite(res$value))) {
    stop("no bucket order satisfies bucketsizes")
  }
  top <- which(res$value >= max(res$value) - tol)
  cons <- unique(reordering(t(res$rankings[, top, drop = FALSE])))
  tau <- bolt_obj_impl(t(cons), cij) / (nj * N * (N - 1))
  if (ps) {
    message("BOLT: ", nrow(S), " starting solutions, ", nrow(cons),
            " solution(s) with Tau = ", round(max(tau), 5))
  }
  list(Consensus = cons, Tau = if (nrow(cons) == 1) tau else matrix(tau, ncol = 1))
}

# starting solutions: computed from cij, given by the user (seeds) and four
# perturbations of the best of them; one in each row, dense rankings
boltseeds <- function(cij, seeds = NULL, full = FALSE) {

  N <- ncol(cij)
  d <- cij - t(cij)
  sig <- cij + t(cij)
  S <- rbind(boltrank(rowSums(d)),             # net flow (Borda)
             boltrank(rowSums(sign(d))),       # Copeland
             boltmarkov(d),                    # Markov chain score
             boltpivot(d, sig),                # bucket pivot order
             findconsensusBB(cij))             # starting point of the BB algorithm
  if (!is.null(seeds)) {
    seeds <- as.matrix(seeds)
    if (ncol(seeds) != N) stop("seeds must have ", N, " columns")
    S <- rbind(S, t(apply(seeds, 1, boltdense)))
  }
  if (full) S <- t(apply(S, 1, rank, ties.method = "first"))
  S <- t(apply(S, 1, boltdense))

  # four perturbations of the best starting solution
  val <- bolt_obj_impl(t(S), cij)
  P <- boltperturb(S[which.max(val), ], 4, max(2, floor(N / 20)))
  unique(rbind(S, P))
}

# rankings of the judges used as starting solutions: the distinct rows of X,
# the most frequent first, at most maxjudges (missing objects tied last)
boltjudges <- function(X, wk, maxjudges) {
  if (maxjudges <= 0) return(NULL)
  X[is.na(X)] <- max(X, na.rm = TRUE) + 1
  key <- apply(X, 1, paste, collapse = " ")
  w <- if (is.null(wk)) rep(1, nrow(X)) else as.numeric(wk)
  tot <- tapply(w, key, sum)
  first <- X[match(names(tot), key), , drop = FALSE]
  first <- first[order(-tot, seq_along(tot)), , drop = FALSE]
  first[seq_len(min(nrow(first), maxjudges)), , drop = FALSE]
}

# dense ranking 1, 2, ... (ties share the same value)
boltdense <- function(r) {
  match(r, sort(unique(r)))
}

# ranking from a score (the larger the better; equal scores are tied)
boltrank <- function(score) {
  boltdense(-score)
}

# stationary distribution of a random walk moving from each object to the
# objects that beat it, with weights the positive net preferences
boltmarkov <- function(d, damp = 0.85, iter = 1000) {
  N <- nrow(d)
  Q <- pmax(t(d), 0)
  rs <- rowSums(Q)
  Q[rs == 0, ] <- 0
  diag(Q)[rs == 0] <- 1
  Q <- Q / rowSums(Q)
  p <- rep(1 / N, N)
  for (it in seq_len(iter)) {
    new <- damp * drop(p %*% Q) + (1 - damp) / N
    done <- max(abs(new - p)) < 1e-14
    p <- new
    if (done) break
  }
  boltrank(round(p, 12))
}

# bucket pivot order (least indecision pivot): the pivot is the most "decided"
# object, the others are tied with it, before it or after it
boltpivot <- function(d, sig) {
  N <- nrow(d)
  r <- integer(N)
  b <- 0L
  # stack of groups still to split (done = FALSE) and of buckets ready to be
  # placed (done = TRUE); the top of the stack is always the leftmost element,
  # so the buckets are placed from the best to the worst
  stack <- list(list(items = seq_len(N), done = FALSE))
  while (length(stack) > 0) {
    top <- stack[[length(stack)]]
    stack[[length(stack)]] <- NULL
    items <- top$items
    if (top$done || length(items) == 1) {
      b <- b + 1L
      r[items] <- b
      next
    }
    piv <- items[which.max(rowSums(abs(d[items, items, drop = FALSE])))]
    rest <- items[items != piv]
    tie <- rest[sig[piv, rest] > abs(d[piv, rest])]
    rest <- rest[!rest %in% tie]
    bef <- rest[d[rest, piv] > 0]
    aft <- rest[!rest %in% bef]
    if (length(aft) > 0) stack[[length(stack) + 1]] <- list(items = aft, done = FALSE)
    stack[[length(stack) + 1]] <- list(items = c(piv, tie), done = TRUE)
    if (length(bef) > 0) stack[[length(stack) + 1]] <- list(items = bef, done = FALSE)
  }
  r
}

# k perturbations of a ranking, each with nswap random adjacent transpositions
# of its order; the generator is internal (Park-Miller, fixed seed), so the
# random number generator of R is not used
boltperturb <- function(r, k, nswap) {
  N <- length(r)
  out <- matrix(0, k, N)
  if (N < 2) return(matrix(r, k, N, byrow = TRUE))
  state <- 20260722
  for (h in seq_len(k)) {
    p <- order(r, seq_len(N))
    for (s in seq_len(nswap)) {
      state <- (16807 * state) %% 2147483647
      i <- 1 + state %% (N - 1)
      p[c(i, i + 1)] <- p[c(i + 1, i)]
    }
    out[h, p] <- seq_len(N)
  }
  out
}
