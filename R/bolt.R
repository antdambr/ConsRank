#' BOLT algorithm for the median ranking
#'
#' Find the median ranking according to the Kemeny's axiomatic approach with
#' BOLT (Bucket-Order Local search with optimal Tie partitioning), a
#' deterministic and scalable heuristic that works entirely on the combined
#' input matrix.
#'
#' @param X A N by M data matrix, in which there are N judges and M objects to
#'   be judged. Each row is a ranking of the objects which are represented by
#'   the columns. If X contains the rankings observed only once, the argument wk
#'   can be used. Either X or cij must be given
#' @param wk Optional: the frequency of each ranking in the data
#' @param full Logical. If TRUE, the median ranking is searched in the space of
#'   full rankings (permutations), i.e. without ties. Default FALSE
#' @param otp Logical. If TRUE (default), the local search is alternated with the
#'   exact optimal tie partitioning (the "full" configuration of the paper); if
#'   FALSE, only the tie-aware local search is used (the "fast" configuration).
#'   Ignored when \code{full = TRUE}
#' @param maxjudges Maximum number of distinct rankings of the judges used as
#'   starting solutions, the most frequent first. Default Inf (all of them);
#'   0 uses only the starting solutions computed from the combined input matrix
#' @param ps Logical. If TRUE, displays information on screen. Default FALSE
#' @param cij The combined input matrix (M by M, see \code{\link{combinpmatr}}),
#'   to be given instead of X. With cij, the argument wk is ignored and the
#'   rankings of the judges are not used as starting solutions
#' @param nj The number of judges (the sum of the weights, if any) that produced
#'   cij. Required when cij is given: it is used to compute the averaged TauX
#'
#' @return A list containing the following components:
#' \tabular{lll}{
#'   Consensus \tab \tab the consensus ranking(s)\cr
#'   Tau \tab \tab averaged TauX rank correlation coefficient\cr
#'   Eltime \tab \tab elapsed time in seconds
#' }
#'
#' @details
#' The median ranking maximizes the averaged TauX rank correlation coefficient
#' with the rankings of the judges, which depends on the data only through the
#' combined input matrix C (Emond and Mason, 2002). BOLT works entirely on C and
#' combines three ingredients:
#' \enumerate{
#'   \item starting solutions computed from C (net flow, Copeland, a Markov chain
#'   score, a bucket pivot order and the starting solution of the branch-and-bound
#'   algorithm), the rankings of the judges and four perturbations of the best of
#'   them;
#'   \item a tie-aware insertion local search: an object is moved to another
#'   position or tied with a group of objects, and each move is evaluated in O(M)
#'   time;
#'   \item the optimal tie partitioning: for a fixed order of the objects, the tie
#'   structure maximizing TauX is computed exactly by dynamic programming in
#'   O(M^2) time.
#' }
#' The local search and the optimal tie partitioning are alternated until no
#' improvement, from each starting solution; the best solution(s) are returned.
#' The procedure is deterministic: the perturbations are generated by an internal
#' generator with a fixed seed, and the random number generator of R is not used.
#'
#' Instead of the data X, the combined input matrix cij can be given, together
#' with the number of judges nj.
#'
#' @examples
#' data(EMD)
#' CR <- bolt(EMD[, 1:15], wk = EMD[, 16])
#' CR$Consensus
#' CR$Tau
#' # the same result from the combined input matrix
#' CR2 <- bolt(cij = combinpmatr(EMD[, 1:15], EMD[, 16]), nj = sum(EMD[, 16]),
#'             maxjudges = 0)
#'
#' @references
#' Romano, M., D'Ambrosio, A., and Conversano, C. A deterministic and scalable
#' heuristic for median ranking detection: tie-aware local search with optimal
#' tie partitioning on the combined input matrix. Manuscript under review.
#'
#' Emond, E. J., and Mason, D. W. (2002). A new rank correlation coefficient with
#' application to the consensus ranking problem. Journal of Multi-Criteria
#' Decision Analysis, 11(1), 17-28.
#'
#' @author Maurizio Romano
#'
#' @seealso \code{\link{consrank}}, \code{\link{mcbo}}, \code{\link{combinpmatr}}
#'
#' @keywords Median ranking
#' @keywords Consensus ranking
#' @keywords Bucket order
#'
#' @export

bolt <- function(X = NULL, wk = NULL, full = FALSE, otp = TRUE, maxjudges = Inf,
                 ps = FALSE, cij = NULL, nj = NULL) {

  tic <- proc.time()[3]
  cij <- checkXcij(X, cij, nj, wk)
  if (!is.null(cij)) {
    out <- boltcij(cij, nj, full = full, otp = otp, seeds = NULL, ps = ps)
    colnames(out$Consensus) <- colnames(cij)
    out$Eltime <- proc.time()[3] - tic
    return(out)
  }
  if (is(X, "data.frame")) X <- as.matrix(X)
  if (is.null(nrow(X))) X <- matrix(X, nrow = 1)
  N <- ncol(X)

  if (nrow(X) == 1) {
    OJ <- onejudge(X, full)  # single judge (ties broken if full = TRUE)
    return(list(Consensus = reordering(OJ$consensus), Tau = OJ$tau, Eltime = proc.time()[3] - tic))
  }
  if (!is.null(wk)) {
    wk <- as.numeric(wk)
    if (length(wk) != nrow(X)) stop("Length of wk must equal number of rows in X")
  }

  cij <- combinpmatr(X, if (is.null(wk)) NULL else matrix(wk, ncol = 1))
  nj <- if (is.null(wk)) nrow(X) else sum(wk)

  judges <- boltjudges(X, wk, maxjudges)
  out <- boltcij(cij, nj, full = full, otp = otp, seeds = judges, ps = ps)
  colnames(out$Consensus) <- colnames(X)
  out$Eltime <- proc.time()[3] - tic
  out
}


